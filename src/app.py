"""
High School Activities API

A simple FastAPI application that lets students view activities and teachers
manage signups at Mergington High School.
"""

import os
import secrets
import time
from pathlib import Path

from fastapi import Depends, FastAPI, HTTPException, Request
from fastapi.responses import JSONResponse, RedirectResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel

app = FastAPI(title="Mergington High School API",
              description="API for viewing and signing up for extracurricular activities")

# Mount the static files directory
current_dir = Path(__file__).parent
app.mount("/static", StaticFiles(directory=os.path.join(Path(__file__).parent,
          "static")), name="static")

SESSION_COOKIE = "teacher_session"
SESSION_LIFETIME_SECONDS = 8 * 60 * 60
teacher_sessions: dict[str, float] = {}


class TeacherLogin(BaseModel):
    username: str
    password: str


def require_teacher(request: Request) -> str:
    token = request.cookies.get(SESSION_COOKIE)
    expires_at = teacher_sessions.get(token) if token else None
    if expires_at is None or expires_at <= time.time():
        if token:
            teacher_sessions.pop(token, None)
        raise HTTPException(status_code=401, detail="Teacher login required")
    return token


